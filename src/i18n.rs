//! UI strings in Portuguese and English. The current language is global so the
//! engine (error and progress messages) and the UI speak the same language.

use std::sync::atomic::{AtomicU8, Ordering};

use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum Lang {
    Pt,
    En,
}

impl Lang {
    pub fn name(self) -> &'static str {
        match self {
            Lang::Pt => "Português",
            Lang::En => "English",
        }
    }
}

static CURRENT: AtomicU8 = AtomicU8::new(1);

pub fn set(lang: Lang) {
    CURRENT.store(lang as u8, Ordering::Relaxed);
}

pub fn current() -> Lang {
    if CURRENT.load(Ordering::Relaxed) == Lang::Pt as u8 { Lang::Pt } else { Lang::En }
}

/// System language: Portuguese for `pt*` locales, English for everything else.
pub fn system() -> Lang {
    match sys_locale::get_locale() {
        Some(l) if l.to_lowercase().starts_with("pt") => Lang::Pt,
        _ => Lang::En,
    }
}

/// Strings for the current language.
pub fn tr() -> &'static Texts {
    match current() {
        Lang::Pt => &PT,
        Lang::En => &EN,
    }
}

/// Replaces the first `{}` in `template` with `value`.
pub fn fill(template: &str, value: impl std::fmt::Display) -> String {
    template.replacen("{}", &value.to_string(), 1)
}

